"""Lean 4 certificate emitter: the ITP component of the reference engine.

The bridge maps proof tasks solved on the manifold and refuted by the
resolution engine into Lean 4 declarations. The emitted file is an artifact
to be kernel-checked by the pinned toolchain (leanprover/lean4:4.14.0); CI
runs `lake env lean` on it. The emission is deterministic: the same task list
always produces the same bytes.

Honest scope: the emitted `tauto` proofs are re-derived by Lean, not imported
from the Python engine. The bridge therefore transfers *tasks*, and Lean
re-proves them. This is the ITP-verification boundary; claiming that the
Python engine "is verified" because its output compiles would violate the
refinement rule (DEP&CC 2.0, Chapter 19.6) and is not claimed.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class LeanTask:
    """One proof task to emit as a Lean theorem.

    Attributes:
      name: theorem name (ASCII identifier).
      prop_vars: propositional variables, in declaration order.
      hypotheses: Lean formulas (strings) as hypothesis types.
      conclusion: Lean formula (string) as the conclusion type.
    """

    name: str
    prop_vars: list[str]
    hypotheses: list[str]
    conclusion: str


HEADER = """\
/-
Generated by bridges/igtp_engine/lean_bridge.py. DO NOT EDIT.
Checked by CI with the pinned toolchain (leanprover/lean4:4.14.0).
Each declaration is re-proved by the Lean kernel; the Python engine's
derivation is a search hint, not a trusted input.
-/
import IGTP
"""


def emit_lean_certificate(tasks: list[LeanTask]) -> str:
    """Emit the Lean certificate file for the given tasks.

    Deterministic: tasks are emitted in sorted name order; hypotheses carry
    generated binder names h1..hk in list order.
    """
    lines = [HEADER]
    for task in sorted(tasks, key=lambda t: t.name):
        binders = " ".join(
            f"{{{v} : Prop}}" for v in task.prop_vars
        )
        hyp_binders = " ".join(
            f"(h{i} : {hyp})" for i, hyp in enumerate(task.hypotheses, start=1)
        )
        lines.append(
            f"theorem {task.name} {binders} {hyp_binders} : {task.conclusion} := by\n  tauto"
        )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
